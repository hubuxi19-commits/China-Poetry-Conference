create table if not exists public.scores (
  id              bigint generated by default as identity primary key,
  nickname        text        not null check (char_length(nickname) between 1 and 20),
  fingerprint     text        not null unique,            -- 一个浏览器只能提交一次
  correct_count   int         not null check (correct_count between 0 and 10),
  total_questions int         not null default 10,
  duration_ms     int         not null check (duration_ms > 0),
  created_at      timestamptz not null default now()
);

-- 排名用索引：分数优先，同分比时间
create index if not exists scores_rank_idx
  on public.scores (correct_count desc, duration_ms asc);

-- 开启行级安全：只允许「读全部 + 插一条」，不允许改和删
alter table public.scores enable row level security;

drop policy if exists "read_all" on public.scores;
create policy "read_all"
  on public.scores for select
  using (true);

drop policy if exists "insert_all" on public.scores;
create policy "insert_all"
  on public.scores for insert
  with check (true);

-- 注意：没有 update / delete 策略，因此已提交的成绩无法被任何人篡改或删除。

